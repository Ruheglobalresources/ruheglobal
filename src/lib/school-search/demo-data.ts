export function pickDemoSchools(country: string, count: number): RawSchool[] {
  const matches = DEMO_SCHOOLS.filter(
    (s) => s.country?.toLowerCase() === country.toLowerCase(),
  );
  const pool = matches.length > 0 ? matches : DEMO_SCHOOLS;
  return pool.slice(0, Math.max(1, Math.min(count, pool.length)));
}
