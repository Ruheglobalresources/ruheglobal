// Starter data for the Country and University tables: every African country with its best known
// and most visited universities. The list is a starting point, not a final one: after seeding,
// countries and universities are edited in the database (admin screens or Prisma Studio) and the
// seed never overwrites those edits (see prisma/seed-countries.ts).
//
// HOW TO READ THE LISTS
//   - Order matters: the first name is shown first in the dropdown (it becomes `order` 0, 1, 2...).
//   - A name starting with "~" is a private university. No mark = public.
//   - Nigeria has the longest list on purpose. Every other country has its main universities.
//   - Top of the Nigeria list follows the July 2026 Webometrics ranking of Nigerian universities
//     (Ibadan, Lagos, Nsukka, Covenant, Landmark), then the other well-known ones.
//
// To add a country: add one object below. To add a university: add its name to that country's list.

